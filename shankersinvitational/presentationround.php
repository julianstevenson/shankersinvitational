				<h3>On The Day</h3>
				<p class="lead">
				
In a morning that was colder than a bucket of penguin shit, there was a warm glow emanating from the Shankers group. </p>


<p>Four people would have rocked up today thinking they were a shoe in for the most committed tour member. 
There was Dolphin who was back from Bali so recently that he was haggling in the pro shop about the price of refreshments. 
Our reigning champion who had reorganised a day off work at short notice due to an error in communication.
Purple, who's new found love of the game usually sees him teeing off on a Sunday 100 metres from home in his shiny new golf cart. He'd ditched that to join the shakers boys... </p>

<p>But there can only be one most committed tour member, and that goes to the Marker for turning up 5 weeks after knee surgery and walking the front nine. Marker even had a cheeky drive on one hole and managed to out do his playing partners.
The examples above bring a lump to the throat, a tear to the eye and some movement to the pants. Knowing the love and dedication to the Shankers Invitational Tournament is still strong and grows by the year.
The trophy is now with Rim Job in it's rightful place until next years tournament. Rumour has it that the fiancé may be relocated to the shed so that the trophy can join Rimmer in the bedroom. Rimmer, just make sure it's clean and sanitised when you bring it to next years tournament please mate.
</p>

<p>More details on next years event will come through soon with confirmed costs, dates etc. 
But as discussed;
<ul>
<li>2016 is the Shankers Victorian Road Trip - a minibus tour of some of Victoria's best courses.</li>
<li>2017 Sheep Shankers - ShIT goes international to New Zealand.</li>
</ul>
</p>
<p>
So onto the seeding. As usual the Seeding Tour allows our competitors to get some form for the main event, whilst also giving our handicapper the chance to run sample scores through the 12 Shankers super computers which finalise tournament handicaps.
This year there's added incentive on the Seeding Tour. For every 30 stableford points scored ​aggregated ​across the seeding events, Shankers competitors will earn 1 Tournament ​P​oint towards their base starting score for the ​2016 ​tournament.
</p>
