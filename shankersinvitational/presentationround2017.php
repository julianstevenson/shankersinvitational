				<h3>On The Day</h3>
				<p class="lead">
				
Following the longest wait in Shankers history for presentation of the trophy, the 2017 champ became the 5th Shanker to see his name etched in Shankers history on the famous ShIT Trophy. </p>

<p>With 2 hardy Shankers giving the event the quorum it needed to be considered part of the official Shankers program,the 2017 Presentation Round was one to remember for those who could be bothered to go.  While some have questioned Moley's commitment to Shankers after missing the 2017 tournament due to the trifling excuse of a newborn ("well it didn't stop Marker in 2016", some have commented), his failure to attend the first event of the 2018 calendar created more rumours than that chick from Suits being seen with a ginger curly one hanging from her mouth.  Equally, sonar-silence from Dolphin suggested he too was considering whether his failure to re-claim the Shankers trophy in 2017 was reason to pack up the clubs and take up Trugo full time.</p>

<p>Only Marker had good reasons for his failure to attend the presentation round.  His trip back to Blighty would have been centred around a mission to learn more about the great game, spending much of his time enjoying the home of [pub] golf in the pubs of Royal Berks.
Thankfully, Hungry and Pussy showed true Shankers commitment, and joined by regular guest Shanker Irish Andrew "The Bloodsucker", along with a first time guest player from Envato called Emile "the Gunner", it was another successful Shankers event.				
				</p>
			<p>Starting proceedings with the presentation of the trophy to 2017 champ, Hungry brought a glow to the heart and a warm fuzzy feeling to Pussy's pink NAGA balls.  Never has there been a more desperate champ and you could see what this meant to Hungry the second he stepped out his car.  Not only did he remember to bring the winners balls to the tee, he was sporting the famous, lost Shankers polo that hasn't been seen since his dismal and humiliating showing at the 2016 competition.</p>

<p>With Hungry hitting the first ball of the 2018 Shankers calender, he tonked it straight down the first fairway, followed up with a great approach shot and two puts for steady handed return to competition golf.  The handicapping Gods had been kind to hungry.  His 7 handicap was converted into a 10 handicap for the day, but this didn't mask the fact that he has his work cut out this year to back up last years success with a brutal handicap. Hungry proceeded to play a steady, yet unexceptional round.  Wayward shots with the driver saw him revert to the tried and tested lob wedge of the tee at times, but his consistently high quality approach shots resulted in a respectable, if unspectacular score of 24 for the day.  Still, he hardly cared about his score on the day, such was his delight and excitement at showing off his trophy to Mrs and mini-Hungry.
</p>
<p>Pussy had been spending the prolonged off season sneaking in some practice at the range when he should have been adding value to the Envato empire on a Thursday afternoon.  Feeling confident, if (not for the first time) a little rusty after a late one on the sauce the night before, Pussy's unspectacular first shot of the tee proved to be one of his better moments on the front nine.  Sporting a fetching pink cap and making the most of having high visibility pink balls, he attempted to hit the ball into every single tree linig the fairways of the leafy front nine.  By the 9th though, Pussy had corrected his course, was keeping his head down and started playing a few half decent shots that included an off-green putt that resulted in his first birdie since that under-14 school disco back in his hey-day.  With 20 more shots to fluff than Hungry, Pussy made a respectable 33 points on the day to go home happy but unfulfilled, not for the first time.</p>

<p>And so another Shankers season has begun.  The first seeding event has been scheduled and the location of the 2018 tournament has been announcemed as <a href="/tour2018.php">Yarrawonga</a>.  Great to be back and this year could prove to be a classic.</p>
 	
						
