				<h1>Rules &amp; Definitions</h1>
				
				<p class="lead">The Shankers Invitational Tournament Organising Committee (ShITOC) take rules very seriously.  Traditional golfing rules apply, in addition to local tournament rules (which are subject to change at the whim of ShITOC)</p>
				
