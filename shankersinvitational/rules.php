				      <h4>Daily NAGA Duties</h4>
				      <ul class="list-2">
 					<li>Whomever is the NAGA after scores have been tallied for a particular day shall purchase other competitors a round of beer from their own money outside of any shout cycles or kitties.</li>
					<li>NAGA singlet must be worn by the recipient (over a polo/t-shirt) from the moment awarded until such time ShITOC take it back from the current recipient at the end of the next round.</li>

					<li>The NAGA is expected to look after the rest of the competitors for the evening, going to the bar to order (but not necessarily pay for) all rounds of drinks until the 12am reverse curfew.</li>
					<li>The NAGA is also expected to do a morning coffee run for competitors.</li>
					<li>NAGA Singlets may be removed when in the bathroom of the accommodation dwelling, and when the recipient goes to bed for the evening but must be worn ALL other times including but not limited to; at a bar, when congregating for drinks in a room, at restaurants, on the course, out and about in general.</li>

				      </ul>
				      <h4>Daily Leader Duties</h4>
				      <ul class="list-2">
						<li>Whomever is in the lead after scores have been tallied for a particular day will be required to do a "leaders shot" of a spirit at evening drinks or dinner.</li>
					<li>Leaders singlet must be worn by the recipient (over a polo/t-shirt) from the moment awarded until such time ShITOC take it back from the current recipient at the end of the next round.</li>

