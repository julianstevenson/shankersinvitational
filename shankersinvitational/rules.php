				      </ul>
                                      <h4>Best Dressed Shanker Day</h4>
                                      <ul class="list-2">
                                                <li>Day 2 of the tournament will be "Best Dressed Shanker" Day.</li>
<li>Best Dressed Shanker will be voted upon by secret ballot by all shankers before the start of play on Day 2. Votes are kept secret and announced by the Tournament Steward at the end of the day when scores are tallied. </li>
<li>Shankers are encouraged to choose wisely as best dressed  attire must be worn to play the round in. No changing after voting. </li>
<li>There is no restriction only imagination but Shankers are reminded that there is some dress code that applies to golf. </li>
<li>The winner of Best Dressed will have a bonus power play applied to their first hole (if they chose to use a PP on hole one it will be applied to the second and so on and so forth until a non power play hole is identified)</li>

</ul>				      	
	
				      
				      <h4>Scoring</h4>
				      <ul class="list-2">
						<li>As this is a competition, competitors are to have their scorecard marked by another competitor (marker) and signed by the marker at the end of each days play.</li>
					<li>Power Plays must be announced before teeing off on the hole. When a Power Play is announced, the marker shall put an asterisk against that hole on the competitor's scorecard. Power Play holes count for double Stableford points. Use them wisely!</li>
<li>All tournament scorecards must be signed by another player and completed in accordance with Social Golf Club rules for submission towards handicaps</li>
				

					
				      </ul>
				      <h4>Other Rules</h4>
				      <ul class="list-2">
                                        <li>Competitors must stay out and enjoy festivities until at least 12 am.</li>
					<li>Non-attendance at the Official Shankers Dinner will result in a tournament penalty to be decided by the Tournament Steward, as well as a double-shot penalty to be consumed prior to the next day's round.</li>
						<li>Failure to comply with the above rules will result in a penalty in the next round or disqualification from the tournament depending on the severity of the transgression.</li>

					
				      </ul>
				      	
	
				      
